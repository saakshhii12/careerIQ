ALTER TABLE public.resumes ADD COLUMN IF NOT EXISTS parsed_data JSONB;

-- Application matching + quiz gate tracking
ALTER TABLE public.applications ADD COLUMN IF NOT EXISTS match_score NUMERIC(5,2);
ALTER TABLE public.applications ADD COLUMN IF NOT EXISTS match_details JSONB;
ALTER TABLE public.applications ADD COLUMN IF NOT EXISTS quiz_status VARCHAR(30) DEFAULT 'Not Started';
ALTER TABLE public.applications ADD COLUMN IF NOT EXISTS quiz_passed BOOLEAN DEFAULT FALSE;
ALTER TABLE public.applications ADD COLUMN IF NOT EXISTS best_quiz_score NUMERIC(5,2);

-- Job skill requirement flag
ALTER TABLE public.job_skills ADD COLUMN IF NOT EXISTS is_required BOOLEAN DEFAULT TRUE;

-- Interview session lifecycle
ALTER TABLE public.interview_sessions ADD COLUMN IF NOT EXISTS status VARCHAR(30) DEFAULT 'Scheduled';
ALTER TABLE public.interview_sessions ADD COLUMN IF NOT EXISTS duration_seconds INTEGER;

-- Richer final evaluation storage
ALTER TABLE public.interview_evaluation ADD COLUMN IF NOT EXISTS overall_score NUMERIC(5,2);
ALTER TABLE public.interview_evaluation ADD COLUMN IF NOT EXISTS problem_solving_score NUMERIC(5,2);
ALTER TABLE public.interview_evaluation ADD COLUMN IF NOT EXISTS recommendation TEXT;
ALTER TABLE public.interview_evaluation ADD COLUMN IF NOT EXISTS strengths TEXT;
ALTER TABLE public.interview_evaluation ADD COLUMN IF NOT EXISTS weaknesses TEXT;

-- Quiz attempts (job-specific gate before AI interview)
CREATE TABLE IF NOT EXISTS public.quiz_attempts (
    attempt_id SERIAL PRIMARY KEY,
    application_id INTEGER NOT NULL REFERENCES public.applications(application_id) ON DELETE CASCADE,
    student_id INTEGER NOT NULL REFERENCES public.students(student_id) ON DELETE CASCADE,
    job_id INTEGER NOT NULL REFERENCES public.jobs(job_id) ON DELETE CASCADE,
    score NUMERIC(5,2),
    passed BOOLEAN DEFAULT FALSE,
    total_questions INTEGER NOT NULL DEFAULT 10,
    correct_answers INTEGER DEFAULT 0,
    started_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP WITHOUT TIME ZONE,
    status VARCHAR(20) DEFAULT 'In Progress'
);

CREATE TABLE IF NOT EXISTS public.quiz_questions (
    question_id SERIAL PRIMARY KEY,
    attempt_id INTEGER NOT NULL REFERENCES public.quiz_attempts(attempt_id) ON DELETE CASCADE,
    question_text TEXT NOT NULL,
    options JSONB NOT NULL,
    correct_option_index INTEGER NOT NULL,
    question_order INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS public.quiz_answers (
    answer_id SERIAL PRIMARY KEY,
    attempt_id INTEGER NOT NULL REFERENCES public.quiz_attempts(attempt_id) ON DELETE CASCADE,
    question_id INTEGER NOT NULL REFERENCES public.quiz_questions(question_id) ON DELETE CASCADE,
    selected_option_index INTEGER,
    is_correct BOOLEAN
);

