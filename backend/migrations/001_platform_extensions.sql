ALTER TABLE public.quiz_questions ADD COLUMN IF NOT EXISTS attempt_id INTEGER;
ALTER TABLE public.quiz_questions ADD COLUMN IF NOT EXISTS question_id BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE public.quiz_questions ADD COLUMN IF NOT EXISTS question_text TEXT;
ALTER TABLE public.quiz_questions ADD COLUMN IF NOT EXISTS options JSONB;
ALTER TABLE public.quiz_questions ADD COLUMN IF NOT EXISTS correct_option_index INTEGER;
